"""Requirement-to-test traceability for VigilWatch.

    python scripts/traceability.py            # print the matrix
    python scripts/traceability.py --write    # refresh docs/design/traceability.md
    python scripts/traceability.py --check    # exit 1 on an uncovered story or unknown ID

Stories are `### VW-nnn: title` headings in docs/design/requirements.md. A test proves a story when
its file mentions the ID (pytest.mark.req, Gherkin tag, or a `req:` comment).
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS = ROOT / "docs" / "design" / "requirements.md"
MATRIX = ROOT / "docs" / "design" / "traceability.md"

STORY = re.compile(r"^### (VW-\d{3}): (.+)$")
REFERENCE = re.compile(r"VW-\d{3}")
CRITERIA_HEADING = "**Acceptance:**"

# (glob relative to ROOT, layer label). The first matching entry wins.
TEST_LOCATIONS = [
    ("tests/unit/**/*.py", "unit"),
    ("tests/integration/**/*.py", "mock"),
    ("tests/mock/**/*.py", "mock"),
    ("tests/contract/**/*.py", "contract"),
    ("tests/e2e/**/*.py", "e2e"),
    ("tests/features/**/*.feature", "bdd"),
    ("tests/step_defs/**/*.py", "bdd"),
    ("tests/test_*.py", "policy"),
    ("frontend/tests/**/*.js", "frontend"),
    ("terraform/tests/**/*.tftest.hcl", "infrastructure"),
]
SELF = "tests/test_traceability.py"


def load_requirements(path: Path = REQUIREMENTS) -> list[dict]:
    stories: list[dict] = []
    current = None
    in_criteria = False
    for line in path.read_text(encoding="utf-8").splitlines():
        heading = STORY.match(line)
        if heading:
            current = {"id": heading.group(1), "title": heading.group(2).strip(), "acceptance": []}
            stories.append(current)
            in_criteria = False
        elif current is None:
            continue
        elif line.startswith("#"):  # a section heading ends the story
            current, in_criteria = None, False
        elif line.strip() == CRITERIA_HEADING:
            in_criteria = True
        elif in_criteria and line.startswith("- "):
            current["acceptance"].append(line[2:].strip())
    return stories


def _test_files() -> list[tuple[str, str]]:
    seen: dict[str, str] = {}
    for pattern, layer in TEST_LOCATIONS:
        for path in sorted(ROOT.glob(pattern)):
            relative = path.relative_to(ROOT).as_posix()
            if relative == SELF or "node_modules" in path.parts or "__pycache__" in path.parts:
                continue
            seen.setdefault(relative, layer)
    return sorted(seen.items())


def scan_references() -> dict[str, list[str]]:
    """Map each cited requirement ID to the test files that cite it."""
    found: dict[str, list[str]] = {}
    for relative, _layer in _test_files():
        text = (ROOT / relative).read_text(encoding="utf-8", errors="replace")
        for ref in sorted(set(REFERENCE.findall(text))):
            found.setdefault(ref, []).append(relative)
    return found


def build_matrix() -> list[dict]:
    references = scan_references()
    layers = dict(_test_files())
    rows = []
    for story in load_requirements():
        files = references.get(story["id"], [])
        rows.append(
            {
                "id": story["id"],
                "title": story["title"],
                "tests": [{"path": f, "layer": layers[f]} for f in files],
            }
        )
    return rows


def render_matrix() -> str:
    lines = [
        "# Requirement traceability",
        "",
        "Generated by `python scripts/traceability.py --write`; do not edit by hand.",
        "A test proves a requirement when its file cites the ID.",
        "Stories are in [requirements.md](requirements.md).",
        "",
        "| Requirement | Layers | Tests |",
        "|---|---|---|",
    ]
    for row in build_matrix():
        layers = ", ".join(sorted({t["layer"] for t in row["tests"]})) or "NONE"
        paths = "<br>".join(f"`{t['path']}`" for t in row["tests"]) or "none"
        lines.append(f"| **{row['id']}** {row['title']} | {layers} | {paths} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="refresh docs/design/traceability.md")
    parser.add_argument("--check", action="store_true", help="fail on gaps or unknown references")
    args = parser.parse_args(argv)

    if args.write:
        MATRIX.write_text(render_matrix(), encoding="utf-8", newline="\n")
        print(f"wrote {MATRIX.relative_to(ROOT)}")
    else:
        print(render_matrix(), end="")

    if args.check:
        known = {s["id"] for s in load_requirements()}
        uncovered = [r["id"] for r in build_matrix() if not r["tests"]]
        unknown = sorted(set(scan_references()) - known)
        if uncovered or unknown:
            print(f"uncovered: {uncovered}  unknown references: {unknown}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
